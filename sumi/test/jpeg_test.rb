def decode(text)
  Jpeg.new(unhex(text)).decode
end

# The mean absolute difference between two decodes of the same picture.
def difference(a, b)
  return 1000.0 if a.pixels.bytesize != b.pixels.bytesize
  total = 0
  i = 0
  while i < a.pixels.bytesize
    total += (a.pixels.getbyte(i) - b.pixels.getbyte(i)).abs
    i += 1
  end
  total.to_f / a.pixels.bytesize
end

