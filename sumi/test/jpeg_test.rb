# A vertical gradient: the top row is dark, the bottom row light.
check("gradient runs dark to light",
      gray_base.pixels.getbyte(0) < 40 && gray_base.pixels.getbyte(32 * 24 - 1) > 215)
check("progressive gradient matches baseline", difference(gray_base, gray_prog) < 3.0)

