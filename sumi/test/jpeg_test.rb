# A truncated image is refused rather than decoded into noise.
short = unhex(T_BASE)
short = short.byteslice(0, 40)
refused = false
begin
  Jpeg.new(short).decode
rescue Filters::DecodeError
  refused = true
rescue Filters::UnsupportedError
  refused = true
end
check("truncated JPEG refused", refused)
