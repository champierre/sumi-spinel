# The JPEG decoder: baseline and progressive, gray and colour.
#
# The four images below are the same two pictures encoded each way, so a
# progressive decode that drifts from the baseline one shows up immediately.
require "sumi"

include Sumi

def check(label, ok)
  puts "#{ok ? 'ok' : 'FAIL'} #{label}"
end

def unhex(text)
  out = String.new
  i = 0
  while i < text.bytesize
    hi = Filters.hex_value(text.getbyte(i))
    lo = Filters.hex_value(text.getbyte(i + 1))
    out << ((hi << 4) | lo).chr
    i += 2
  end
  out
end

